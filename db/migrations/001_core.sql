-- Portable PostgreSQL schema. Application IDs are independent of the auth provider.
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 2 AND 24),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.identity_links (
  provider text NOT NULL,
  subject text NOT NULL,
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  PRIMARY KEY (provider, subject),
  UNIQUE (provider, profile_id)
);
CREATE TABLE public.channels (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 2 AND 32)
);
CREATE TABLE public.messages (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  channel_id integer NOT NULL REFERENCES public.channels(id),
  user_id uuid NOT NULL REFERENCES public.profiles(id),
  body text NOT NULL CHECK (char_length(trim(body)) BETWEEN 1 AND 2000),
  created timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_channel_id_idx ON public.messages(channel_id, id DESC);
