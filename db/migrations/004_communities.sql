CREATE TABLE dm_pairs (pair text PRIMARY KEY,channel_id integer NOT NULL UNIQUE REFERENCES channels(id));
CREATE TABLE invites (
 token_hash text PRIMARY KEY,server_id integer NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
 created_by uuid NOT NULL REFERENCES profiles(id),expires_at timestamptz NOT NULL DEFAULT now()+interval '7 days'
);
