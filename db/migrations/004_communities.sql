CREATE TABLE reactions (
 message_id bigint NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES profiles(id),emoji text NOT NULL CHECK(emoji IN ('👍','❤️','😂','🎉','👀','🔥')),
 PRIMARY KEY(message_id,user_id,emoji)
);
CREATE TABLE channel_reads (
 channel_id integer NOT NULL REFERENCES channels(id),user_id uuid NOT NULL REFERENCES profiles(id),
 last_message_id bigint NOT NULL DEFAULT 0,PRIMARY KEY(channel_id,user_id)
);
CREATE TABLE moderation_log (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,server_id integer REFERENCES servers(id),
 actor_id uuid REFERENCES profiles(id),target_id uuid REFERENCES profiles(id),action text NOT NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE FUNCTION public.join_onde_lobby() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
BEGIN INSERT INTO public.memberships(server_id,user_id) VALUES(1,NEW.id); RETURN NEW; END;
$$;
CREATE TRIGGER join_onde_lobby AFTER INSERT ON profiles FOR EACH ROW EXECUTE FUNCTION public.join_onde_lobby();
REVOKE ALL ON FUNCTION public.join_onde_lobby() FROM PUBLIC;
CREATE TABLE attachments (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),channel_id integer NOT NULL REFERENCES channels(id),
 user_id uuid NOT NULL REFERENCES profiles(id),message_id bigint REFERENCES messages(id),
 name text NOT NULL,mime text NOT NULL,bytes bytea NOT NULL,size integer NOT NULL CHECK(size BETWEEN 1 AND 1048576),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_message_idx ON attachments(message_id);
CREATE INDEX attachments_user_idx ON attachments(user_id);
